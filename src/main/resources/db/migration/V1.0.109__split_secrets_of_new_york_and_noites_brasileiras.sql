CREATE TEMPORARY TABLE release_collection_rows ENGINE=InnoDB AS
SELECT c.id, c.collection_id, c.card_id, p.abbrev, c.number, c.notes,
       FIRST_VALUE(c.id) OVER (
           PARTITION BY c.collection_id, c.card_id, c.condition, c.language, c.binder_id
           ORDER BY (c.`set` = p.abbrev) DESC, c.id
       ) AS keep_id,
       c.`set` <> p.abbrev AS legacy
FROM collection_card c JOIN release_printings p ON p.card_id = c.card_id
WHERE c.`set` IN ('V5SN', p.abbrev) OR c.`set` LIKE 'V5SN:%';

CREATE TEMPORARY TABLE release_collection_totals ENGINE=InnoDB AS
SELECT keep_id, MAX(collection_id) AS collection_id, MAX(card_id) AS card_id,
       MAX(abbrev) AS abbrev, SUM(number) AS quantity,
       GROUP_CONCAT(DISTINCT BINARY NULLIF(notes, '') ORDER BY id SEPARATOR '\n\n') AS notes
FROM release_collection_rows
GROUP BY keep_id HAVING MAX(legacy) = 1;

DELETE c FROM collection_card c
JOIN release_collection_rows r ON r.id = c.id
JOIN release_collection_totals t ON t.keep_id = r.keep_id
WHERE c.id <> r.keep_id;

UPDATE collection_card c JOIN release_collection_totals t ON t.keep_id = c.id
SET c.`set` = t.abbrev, c.number = t.quantity, c.notes = COALESCE(t.notes, c.notes),
    c.modification_date = c.modification_date;

UPDATE collection_card_history h JOIN release_printings p ON p.card_id = h.card_id
SET h.`set` = p.abbrev
WHERE h.id <= @release_history_start AND (h.`set` = 'V5SN' OR h.`set` LIKE 'V5SN:%');

DELETE h FROM collection_card_history h
JOIN release_collection_totals t ON t.collection_id = h.collection_id AND t.card_id = h.card_id
WHERE h.id > @release_history_start;

CREATE TEMPORARY TABLE release_wishlist_rows ENGINE=InnoDB AS
SELECT w.id, p.abbrev, w.number, w.priority, w.notes,
       FIRST_VALUE(w.id) OVER (
           PARTITION BY w.user_id, w.card_id, w.condition, w.language
           ORDER BY (w.`set` = p.abbrev) DESC, w.id
       ) AS keep_id,
       w.`set` <> p.abbrev AS legacy
FROM wishlist_card w JOIN release_printings p ON p.card_id = w.card_id
WHERE w.`set` IN ('V5SN', p.abbrev) OR w.`set` LIKE 'V5SN:%';

CREATE TEMPORARY TABLE release_wishlist_totals ENGINE=InnoDB AS
SELECT keep_id, MAX(abbrev) AS abbrev, SUM(number) AS quantity, MAX(priority) AS priority,
       GROUP_CONCAT(DISTINCT BINARY NULLIF(notes, '') ORDER BY id SEPARATOR '\n\n') AS notes
FROM release_wishlist_rows
GROUP BY keep_id HAVING MAX(legacy) = 1;

DELETE w FROM wishlist_card w
JOIN release_wishlist_rows r ON r.id = w.id
JOIN release_wishlist_totals t ON t.keep_id = r.keep_id
WHERE w.id <> r.keep_id;

UPDATE wishlist_card w JOIN release_wishlist_totals t ON t.keep_id = w.id
SET w.`set` = t.abbrev, w.number = t.quantity, w.priority = t.priority,
    w.notes = COALESCE(t.notes, w.notes), w.modification_date = w.modification_date;

CREATE TEMPORARY TABLE release_market_rows ENGINE=InnoDB AS
SELECT s.id, s.card_id, s.platform, s.locale, s.seller, s.in_stock, s.price_default_currency, s.price,
       CASE
           WHEN s.`set` = 'V5SN' OR s.`set` = CONCAT('V5SN:', p.abbrev) THEN p.abbrev
           WHEN s.`set` LIKE 'V5SN:%' THEN CONCAT(p.abbrev, ':', p.copies)
           ELSE s.`set`
       END AS printing,
       s.`set` = 'V5SN' OR s.`set` LIKE 'V5SN:%' AS legacy
FROM card_shop s JOIN release_printings p ON p.card_id = s.card_id
WHERE s.`set` IN ('V5SN', p.abbrev) OR s.`set` LIKE 'V5SN:%'
   OR s.`set` = CONCAT(p.abbrev, ':', p.copies);

CREATE TEMPORARY TABLE release_market_ranked ENGINE=InnoDB AS
SELECT id, printing, legacy,
       MAX(legacy) OVER (
           PARTITION BY card_id, platform, printing, COALESCE(locale, ''), COALESCE(seller, '')
       ) AS migrated_group,
       ROW_NUMBER() OVER (
           PARTITION BY card_id, platform, printing, COALESCE(locale, ''), COALESCE(seller, '')
           ORDER BY in_stock DESC, COALESCE(price_default_currency, price) IS NULL,
                    COALESCE(price_default_currency, price), legacy, id
       ) AS ranking
FROM release_market_rows;

DELETE s FROM card_shop s JOIN release_market_ranked r ON r.id = s.id
WHERE r.migrated_group AND r.ranking > 1;

UPDATE card_shop s JOIN release_market_ranked r ON r.id = s.id
SET s.`set` = r.printing, s.modification_date = s.modification_date
WHERE r.legacy AND r.ranking = 1;

